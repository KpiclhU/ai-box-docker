#!/usr/bin/env bash
# install.sh — bring up Open WebUI, Open Terminal and OpenClaw on this VM, each
# on its own static LAN address.
#
#   sudo ./install.sh
#
# Re-running is safe. It fills in anything missing from .env, keeps the keys it
# already generated, regenerates open-webui.env from comfy/sdxl.api.json, and
# re-applies the stack.
set -euo pipefail
cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")"

die() { echo "error: $*" >&2; exit 1; }
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }

[ "$(id -u)" -eq 0 ] || die "needs root: sudo $0"
have docker || die "docker is not installed — see proxmox/cloud-init/user-data, or README.md"
docker compose version >/dev/null 2>&1 || die "the docker compose plugin is missing (apt install docker-compose-plugin)"

get() { sed -n "s|^$1=||p" .env 2>/dev/null | tail -1 | tr -d '\r' || true; }
put() { # <key> <value>
  local k="$1" v="$2" esc
  esc="$(printf '%s' "$v" | sed 's/[\\|&]/\\&/g')"
  if grep -qE "^$k=" .env; then
    sed -i "s|^$k=.*|$k=$esc|" .env
  else
    printf '%s=%s\n' "$k" "$v" >> .env
  fi
}
rand() { openssl rand -hex "$1" 2>/dev/null || head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ---- 1. .env and the secrets it must carry ----------------------------------
if [ ! -f .env ]; then
  cp .env.example .env
  echo "created .env from .env.example"
fi
chmod 600 .env

for pair in \
  "OPENWEBUI_SECRET_KEY:32" \
  "OPEN_TERMINAL_API_KEY:24" \
  "OPENCLAW_GATEWAY_TOKEN:24" \
  "OPENWEBUI_ADMIN_PASSWORD:12"; do
  key="${pair%%:*}"
  len="${pair##*:}"
  [ -n "$(get "$key")" ] || put "$key" "$(rand "$len")"
done

# ---- 2. the macvlan parent --------------------------------------------------
parent="$(get LAN_PARENT)"
parent="${parent:-eth0}"
if ! ip link show "$parent" >/dev/null 2>&1; then
  detected="$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')"
  [ -n "$detected" ] || die "cannot find a default-route interface; set LAN_PARENT in .env"
  put LAN_PARENT "$detected"
  echo "LAN_PARENT=$detected (detected; .env said '$parent')"
fi

# ---- 3. the SDXL graph, so the first image needs no import ------------------
NODES='[{"type":"prompt","key":"text","node_ids":["6"]},{"type":"model","key":"ckpt_name","node_ids":["4"]},{"type":"width","key":"width","node_ids":["5"]},{"type":"height","key":"height","node_ids":["5"]},{"type":"steps","key":"steps","node_ids":["3"]},{"type":"seed","key":"seed","node_ids":["3"]}]'
if have python3 && [ -f comfy/sdxl.api.json ]; then
  workflow="$(python3 -c 'import json,sys;print(json.dumps(json.load(open(sys.argv[1])),separators=(",",":")))' comfy/sdxl.api.json)"
  {
    echo "# Generated by install.sh from comfy/sdxl.api.json. Do not edit."
    printf 'COMFYUI_WORKFLOW=%s\n' "$workflow"
    printf 'COMFYUI_WORKFLOW_NODES=%s\n' "$NODES"
  } > open-webui.env
  echo "wrote open-webui.env (SDXL graph, $(printf '%s' "$workflow" | wc -c) bytes of JSON)"
else
  printf '# python3 or comfy/sdxl.api.json missing: import comfy/sdxl.api.json by hand\n' > open-webui.env
  echo "warning: could not build the SDXL graph — import comfy/sdxl.api.json in Admin -> Settings -> Images" >&2
fi

# ---- 4. openclaw's state directory, owned by the image's uid ----------------
mkdir -p openclaw
chown 1000:1000 openclaw
chmod 755 openclaw

# ---- 5. openclaw's config, written before the gateway is ever started -------
# The gateway exits 78 (EX_CONFIG) instead of guessing gateway.mode, so an empty
# state directory is not "unconfigured", it is "invalid" — it would restart forever.
llama_url="$(get LLAMA_URL)"; llama_url="${llama_url:-http://192.168.150.40:8080/v1}"
case "$llama_url" in http://*|https://*) ;; *) llama_url="http://$llama_url" ;; esac
llama_key="$(get LLAMA_API_KEY)"; llama_key="${llama_key:-none}"
claw_ip="$(get OPENCLAW_IP)";   claw_ip="${claw_ip:-192.168.150.53}"
claw_cfg="$PWD/openclaw/openclaw.json"

first_model() { # the id llama-server is serving, straight from /v1/models
  local json
  json="$(curl -fsS --max-time 10 "${llama_url%/}/models" 2>/dev/null)" || return 1
  if have python3; then
    printf '%s' "$json" | python3 -c 'import json,sys;print(json.load(sys.stdin)["data"][0]["id"])' 2>/dev/null && return 0
  fi
  if have jq; then
    printf '%s' "$json" | jq -er '.data[0].id' 2>/dev/null && return 0
  fi
  printf '%s' "$json" | sed -n 's/.*"id"[[:space:]]*:[[:space:]]*"\([^"]*\)".*/\1/p' | head -1
}

claw_mode() { # gateway.mode as it is actually written in openclaw.json
  [ -f "$claw_cfg" ] || return 0
  if have python3; then
    python3 - "$claw_cfg" <<'PY' 2>/dev/null || true
import json, sys
try:
    cfg = json.load(open(sys.argv[1]))
except Exception:
    sys.exit(0)
mode = (cfg.get("gateway") or {}).get("mode")
print(mode if isinstance(mode, str) else "")
PY
  else
    docker compose run -T --rm --no-deps --entrypoint node openclaw \
      --input-type=commonjs -e \
      'const fs=require("fs");try{const c=JSON.parse(fs.readFileSync("/home/node/.openclaw/openclaw.json","utf8"));process.stdout.write(String((c.gateway||{}).mode||""))}catch(e){}' \
      2>/dev/null || true
  fi
}

onboard() { # <model> [extra onboard flags...]
  docker compose run -T --rm --no-deps --entrypoint node openclaw \
    dist/index.js onboard --non-interactive --accept-risk --skip-health \
      --mode local \
      --auth-choice llama-cpp-existing-server \
      --custom-base-url "$llama_url" \
      --custom-model-id "$1" \
      --llama-server-api-key "$llama_key" \
      --gateway-auth token --gateway-token-ref-env OPENCLAW_GATEWAY_TOKEN \
      --gateway-bind lan \
      --skip-channels --no-install-daemon "${@:2}"
}

# A one-off `run` keeps the service's static address, so the long-running
# container must not be holding it while onboarding runs.
docker compose stop openclaw >/dev/null 2>&1 || true

# gateway.mode is onboarding's to write: the gateway refuses to guess it, so a
# config without one — a stub from an older container, or a write that was
# rejected wholesale (see openclaw.json.rejected.*) — is damaged, not unfilled.
# Starting against it only buys an endless "exited with code 78".
mode="$(claw_mode)"
claw_ready=0
if [ -n "$mode" ]; then
  echo "openclaw: openclaw.json already declares gateway.mode=$mode, leaving its provider alone"
  claw_ready=1
else
  model="${LLAMA_MODEL:-}"
  [ -n "$model" ] || model="$(first_model || true)"
  if [ -z "$model" ]; then
    echo "warning: no model from ${llama_url%/}/models — OpenClaw is left stopped" >&2
    echo "         start ai-box and re-run, or set LLAMA_MODEL=<id>" >&2
  elif [ -f "$claw_cfg" ]; then
    echo "openclaw: $claw_cfg has no gateway.mode — repairing it" >&2
    cp -a "$claw_cfg" "$claw_cfg.bak.$(date +%Y%m%d-%H%M%S)"
    say "Onboarding OpenClaw against $llama_url (model $model, repairing config)"
    onboard "$model" --reset --reset-scope config \
      || echo "warning: onboarding exited non-zero (see above)" >&2
    if [ -z "$(claw_mode)" ]; then
      # --reset needs readable config and SQLite; if it could not repair the
      # directory, set it aside rather than starting against it.
      echo "openclaw: reset could not repair the state directory — moving it aside" >&2
      mv openclaw "openclaw.damaged.$(date +%Y%m%d-%H%M%S)"
      mkdir -p openclaw
      chown 1000:1000 openclaw
      chmod 755 openclaw
      onboard "$model" || echo "warning: onboarding exited non-zero (see above)" >&2
    fi
  else
    say "Onboarding OpenClaw against $llama_url (model $model)"
    onboard "$model" || echo "warning: onboarding exited non-zero (see above)" >&2
  fi

  mode="$(claw_mode)"
  if [ -n "$mode" ]; then
    claw_ready=1
  else
    echo "warning: onboarding did not write gateway.mode — OpenClaw stays stopped" >&2
    echo "         (starting it now would only restart-loop on exit 78)" >&2
    echo "         docker compose logs --tail=40 openclaw; ls openclaw/openclaw.json.rejected.*" >&2
  fi
fi

if [ "$claw_ready" -eq 1 ]; then
  # The control UI is opened at the container's own LAN address, which is not
  # loopback, so it has to be listed. Re-applied on every run; a rejected write
  # leaves the config untouched, so this cannot break a working gateway.
  origins="[\"http://$claw_ip:18789\",\"http://localhost:18789\",\"http://127.0.0.1:18789\"]"
  docker compose run -T --rm --no-deps --entrypoint node openclaw \
    dist/index.js config set gateway.controlUi.allowedOrigins "$origins" --strict-json \
    || echo "warning: could not add http://$claw_ip:18789 to gateway.controlUi.allowedOrigins — the Control UI will load but refuse to connect; add it in openclaw/openclaw.json by hand" >&2
fi

# ---- 6. the host-side shim, and a unit so it survives a reboot --------------
ENV_FILE="$PWD/.env" bash ./shim.sh up
cat > /etc/systemd/system/ai-docker-shim.service <<EOF
[Unit]
Description=ai-docker macvlan shim (host -> its own containers)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
Environment=ENV_FILE=$PWD/.env
ExecStart=$PWD/shim.sh up
ExecStop=$PWD/shim.sh down

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable ai-docker-shim.service >/dev/null 2>&1 || true

# ---- 7. the stack -----------------------------------------------------------
say "Starting the stack"
if [ "${claw_ready:-0}" = 1 ]; then
  docker compose up -d --remove-orphans
else
  echo "openclaw has no config yet — starting the other two services only" >&2
  docker compose up -d --remove-orphans open-webui open-terminal
fi

if [ "${claw_ready:-0}" = 1 ]; then
  claw_next="  3. OpenClaw was onboarded against $llama_url during this run:
     http://$claw_ip:18789 — paste the gateway token above."
else
  claw_next="  3. OpenClaw is stopped until ai-box answers on $llama_url:
     start it, then re-run sudo ./install.sh to onboard."
fi

webui_ip="$(get OPENWEBUI_IP)";       webui_ip="${webui_ip:-192.168.150.51}"
term_ip="$(get OPEN_TERMINAL_IP)";    term_ip="${term_ip:-192.168.150.52}"
claw_ip="$(get OPENCLAW_IP)";         claw_ip="${claw_ip:-192.168.150.53}"

wait_for() { # <url> <label>
  local i=0
  while [ "$i" -lt 45 ]; do
    if curl -s -o /dev/null --max-time 2 "$1"; then return 0; fi
    i=$((i+1))
    sleep 2
  done
  echo "  $2 did not answer at $1 after 90 s" >&2
  return 1
}

say "Waiting for the services"
wait_for "http://$webui_ip:8080/health" "open-webui"  || echo "    docker compose logs --tail=30 open-webui" >&2
wait_for "http://$term_ip:8000/docs"    "open-terminal" || echo "    docker compose logs --tail=30 open-terminal" >&2
if [ "${claw_ready:-0}" = 1 ]; then
  wait_for "http://$claw_ip:18789/"     "openclaw"    || echo "    docker compose logs --tail=30 openclaw" >&2
fi

cat <<EOF

  open-webui      http://$webui_ip:8080
                  $(get OPENWEBUI_ADMIN_EMAIL) / $(get OPENWEBUI_ADMIN_PASSWORD)
  open-terminal   http://$term_ip:8000/docs     key: $(get OPEN_TERMINAL_API_KEY)
  openclaw        http://$claw_ip:18789         token: $(get OPENCLAW_GATEWAY_TOKEN)

  these live in .env (mode 600). Treat that file as a secret: the terminal key
  and the gateway token are full control of those two containers.

Next:
  1. Sign in to Open WebUI, change the admin password, create one account per
     person (Admin -> Settings -> Users), then Admin -> Settings -> Connections
     should already list $llama_url.
  2. Add the terminal: Admin -> Settings -> Integrations -> Terminal -> +,
     URL http://$term_ip:8000, key above, auth Bearer.
  ${claw_next}
EOF
