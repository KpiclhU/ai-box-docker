#!/usr/bin/env bash
# install.sh — bring up Open WebUI, Open Terminal and OpenClaw on this VM, each
# on its own static LAN address.
#
#   sudo ./install.sh
#
# Re-running is safe. It fills in anything missing from .env, keeps the keys it
# already generated, regenerates open-webui.env from comfy/sdxl.api.json, and
# re-applies the stack.
set -euo pipefail
cd "$(dirname "$(readlink -f "${BASH_SOURCE[0]}")")"

die() { echo "error: $*" >&2; exit 1; }
say() { printf '\n\033[1m%s\033[0m\n' "$*"; }
have() { command -v "$1" >/dev/null 2>&1; }

[ "$(id -u)" -eq 0 ] || die "needs root: sudo $0"
have docker || die "docker is not installed — see proxmox/cloud-init/user-data, or README.md"
docker compose version >/dev/null 2>&1 || die "the docker compose plugin is missing (apt install docker-compose-plugin)"

get() { sed -n "s|^$1=||p" .env 2>/dev/null | tail -1 | tr -d '\r' || true; }
put() { # <key> <value>
  local k="$1" v="$2" esc
  esc="$(printf '%s' "$v" | sed 's/[\\|&]/\\&/g')"
  if grep -qE "^$k=" .env; then
    sed -i "s|^$k=.*|$k=$esc|" .env
  else
    printf '%s=%s\n' "$k" "$v" >> .env
  fi
}
rand() { openssl rand -hex "$1" 2>/dev/null || head -c "$1" /dev/urandom | od -An -tx1 | tr -d ' \n'; }

# ---- 1. .env and the secrets it must carry ----------------------------------
if [ ! -f .env ]; then
  cp .env.example .env
  echo "created .env from .env.example"
fi
chmod 600 .env

for pair in \
  "OPENWEBUI_SECRET_KEY:32" \
  "OPEN_TERMINAL_API_KEY:24" \
  "OPENCLAW_GATEWAY_TOKEN:24" \
  "OPENWEBUI_ADMIN_PASSWORD:12"; do
  key="${pair%%:*}"
  len="${pair##*:}"
  [ -n "$(get "$key")" ] || put "$key" "$(rand "$len")"
done

# ---- 2. the macvlan parent --------------------------------------------------
parent="$(get LAN_PARENT)"
parent="${parent:-eth0}"
if ! ip link show "$parent" >/dev/null 2>&1; then
  detected="$(ip -4 route show default 2>/dev/null | awk '{print $5; exit}')"
  [ -n "$detected" ] || die "cannot find a default-route interface; set LAN_PARENT in .env"
  put LAN_PARENT "$detected"
  echo "LAN_PARENT=$detected (detected; .env said '$parent')"
fi

# ---- 3. the SDXL graph, so the first image needs no import ------------------
NODES='[{"type":"prompt","key":"text","node_ids":["6"]},{"type":"model","key":"ckpt_name","node_ids":["4"]},{"type":"width","key":"width","node_ids":["5"]},{"type":"height","key":"height","node_ids":["5"]},{"type":"steps","key":"steps","node_ids":["3"]},{"type":"seed","key":"seed","node_ids":["3"]}]'
if have python3 && [ -f comfy/sdxl.api.json ]; then
  workflow="$(python3 -c 'import json,sys;print(json.dumps(json.load(open(sys.argv[1])),separators=(",",":")))' comfy/sdxl.api.json)"
  {
    echo "# Generated by install.sh from comfy/sdxl.api.json. Do not edit."
    printf 'COMFYUI_WORKFLOW=%s\n' "$workflow"
    printf 'COMFYUI_WORKFLOW_NODES=%s\n' "$NODES"
  } > open-webui.env
  echo "wrote open-webui.env (SDXL graph, $(printf '%s' "$workflow" | wc -c) bytes of JSON)"
else
  printf '# python3 or comfy/sdxl.api.json missing: import comfy/sdxl.api.json by hand\n' > open-webui.env
  echo "warning: could not build the SDXL graph — import comfy/sdxl.api.json in Admin -> Settings -> Images" >&2
fi

# ---- 4. openclaw's state directory, owned by the image's uid ----------------
mkdir -p openclaw
chown 1000:1000 openclaw
chmod 755 openclaw

# ---- 5. the host-side shim, and a unit so it survives a reboot --------------
ENV_FILE="$PWD/.env" bash ./shim.sh up
cat > /etc/systemd/system/ai-docker-shim.service <<EOF
[Unit]
Description=ai-docker macvlan shim (host -> its own containers)
After=network-online.target
Wants=network-online.target

[Service]
Type=oneshot
RemainAfterExit=yes
Environment=ENV_FILE=$PWD/.env
ExecStart=$PWD/shim.sh up
ExecStop=$PWD/shim.sh down

[Install]
WantedBy=multi-user.target
EOF
systemctl daemon-reload
systemctl enable ai-docker-shim.service >/dev/null 2>&1 || true

# ---- 6. the stack -----------------------------------------------------------
say "Starting the stack"
docker compose up -d --remove-orphans

webui_ip="$(get OPENWEBUI_IP)";       webui_ip="${webui_ip:-192.168.150.51}"
term_ip="$(get OPEN_TERMINAL_IP)";    term_ip="${term_ip:-192.168.150.52}"
claw_ip="$(get OPENCLAW_IP)";         claw_ip="${claw_ip:-192.168.150.53}"

wait_for() { # <url> <label>
  local i=0
  while [ "$i" -lt 45 ]; do
    if curl -s -o /dev/null --max-time 2 "$1"; then return 0; fi
    i=$((i+1))
    sleep 2
  done
  echo "  $2 did not answer at $1 after 90 s" >&2
  return 1
}

say "Waiting for the services"
wait_for "http://$webui_ip:8080/health" "open-webui"  || echo "    docker compose logs --tail=30 open-webui" >&2
wait_for "http://$term_ip:8000/docs"    "open-terminal" || echo "    docker compose logs --tail=30 open-terminal" >&2
wait_for "http://$claw_ip:18789/"       "openclaw"    || echo "    docker compose logs --tail=30 openclaw" >&2

cat <<EOF

  open-webui      http://$webui_ip:8080
                  $(get OPENWEBUI_ADMIN_EMAIL) / $(get OPENWEBUI_ADMIN_PASSWORD)
  open-terminal   http://$term_ip:8000/docs     key: $(get OPEN_TERMINAL_API_KEY)
  openclaw        http://$claw_ip:18789         token: $(get OPENCLAW_GATEWAY_TOKEN)

  these live in .env (mode 600). Treat that file as a secret: the terminal key
  and the gateway token are full control of those two containers.

Next:
  1. Sign in to Open WebUI, change the admin password, create one account per
     person (Admin -> Settings -> Users), then Admin -> Settings -> Connections
     should already list ${LLAMA_URL:-http://192.168.150.40:8080/v1}.
  2. Add the terminal: Admin -> Settings -> Integrations -> Terminal -> +,
     URL http://$term_ip:8000, key above, auth Bearer.
  3. Finish OpenClaw: docker compose run --rm --no-deps --entrypoint node \\
       openclaw dist/index.js onboard --mode local --no-install-daemon
     and point its model provider at the same llama-server URL.
EOF
